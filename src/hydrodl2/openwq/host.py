"""OpenWQ host side in Python.

Loads the compiled hydrolink module ``openwq_py`` (built from
``<repo>/openwq/OpenWQ_hydrolink.cpp`` with the CMake target ``python_openwq`` of
the OpenWQ clone in ``<repo>/openwq/openwq``, see ``<repo>/openwq/README.md``) and
adds the helpers every Python host model needs: running from the case folder, a
calendar that advances the OpenWQ clock, and a minimal configuration writer.

The module is looked up in ``$OPENWQ_HYDROLINK_DIR`` first, then in
``<repo>/openwq`` (the hydrolink folder of this repository).

Typical use::

    from hydrodl2.openwq import host as openwq
    with openwq.case_dir("/path/to/case"):          # folder with openWQ_master.json
        host = openwq.Host("openWQ_master.json")
        soil = host.add_compartment("SOIL", nx=n_basins)
        host.add_ext_flux("PRECIP", nx=n_basins)
        host.init()
        clock = openwq.Clock(2000, 1, 1, step_hours=24)
        for t in range(n_steps):
            y, m, d, h, mi = clock.at(t)
            host.set_water_volume_array(soil, soil_vol_m3[t])
            host.time_start(y, m, d, h, mi)
            for b in range(n_basins):
                host.inflow("PRECIP", soil, b, 0, 0, rain_m3[t, b], y, m, d, h, mi)
            host.time_end(y, m, d, h, mi)
"""

from __future__ import annotations

import contextlib
import datetime as _dt
import importlib
import json
import os
import sys
from pathlib import Path

HYDROLINK_DIR = Path(__file__).resolve().parents[3] / 'openwq'   # <repo>/openwq


def _load_module():
    candidates = []
    env = os.environ.get('OPENWQ_HYDROLINK_DIR')
    if env:
        candidates.append(Path(env))
    candidates.append(HYDROLINK_DIR)
    for d in candidates:
        if d.is_dir() and any(d.glob('openwq_py*.so')) or d.is_dir() and any(d.glob('openwq_py*.pyd')):
            if str(d) not in sys.path:
                sys.path.insert(0, str(d))
            return importlib.import_module('openwq_py')
    raise ImportError(
        "openwq_py module not found in %s. Build the hydrolink with the CMake target "
        "python_openwq of <repo>/openwq/openwq (see <repo>/openwq/README.md) or set "
        "OPENWQ_HYDROLINK_DIR." % ' or '.join(str(c) for c in candidates))


openwq_py = _load_module()
Host = openwq_py.Host

LOSS = -1  # recipient index meaning "water leaves the domain"


@contextlib.contextmanager
def case_dir(path):
    """chdir() into the case folder for the duration of the block.

    OpenWQ resolves every path of the master JSON relative to the current
    working directory, exactly as the Fortran hosts do.
    """
    prev = os.getcwd()
    os.chdir(str(path))
    try:
        yield Path(path)
    finally:
        os.chdir(prev)


class Clock:
    """Calendar of the host time steps as (year, month, day, hour, minute)."""

    def __init__(self, year, month, day, hour=0, minute=0, step_hours=24.0):
        self.start = _dt.datetime(year, month, day, hour, minute)
        self.step = _dt.timedelta(hours=float(step_hours))

    def datetime(self, t):
        return self.start + t * self.step

    def at(self, t):
        d = self.datetime(t)
        return d.year, d.month, d.day, d.hour, d.minute

    @property
    def step_seconds(self):
        return self.step.total_seconds()


def write_minimal_config(folder, compartments, species=("TRACER",),
                         initial_mg_l=None, ewf_names=("PRECIP",),
                         ewf_mg_l=None, timestep=(1, "day"),
                         flux_exports=(), decay_per_day=0.0,
                         project="python host", units="KG",
                         comment="generated by openwq.write_minimal_config"):
    """Write a complete minimal OpenWQ configuration (master + openwq_in/*) that
    declares one conservative tracer cycle for the given compartments.

    compartments  list of compartment names (as declared on the Host)
    initial_mg_l  dict compartment -> {species: concentration} initial condition
    ewf_mg_l      dict ewf name -> {species: concentration} of the inflow
    flux_exports  names declared with Host.add_flux_export to print
    Returns the master JSON path (relative to ``folder``: "openWQ_master.json").
    """
    folder = Path(folder)
    (folder / "openwq_in").mkdir(parents=True, exist_ok=True)
    (folder / "openwq_out").mkdir(parents=True, exist_ok=True)
    species = list(species)
    initial_mg_l = initial_mg_l or {}
    ewf_mg_l = ewf_mg_l or {}
    allcells = ["all", "all", "all"]

    master = {
        "PROJECT_NAME": project,
        "GEOGRAPHICAL_LOCATION": "python",
        "AUTHORS": "openwq python host",
        "DATE": _dt.date.today().isoformat(),
        "COMMENT": comment,
        "COMPUTATIONAL_SETTINGS": {"RUN_MODE_DEBUG": False, "USE_NUM_THREADS": 1},
        "SOLVER": "FORWARD_EULER",
        "OPENWQ_INPUT": {
            "CONFIG_FILEPATH": "openwq_in/openWQ_config.json",
            "EXTERNAL_WATER_FLUXES": {
                str(i + 1): {"LABEL": name.lower(), "FILEPATH": "openwq_in/openWQ_EWF_%s.json" % name}
                for i, name in enumerate(ewf_names)
            },
        },
        "MODULES": {
            "BIOGEOCHEMISTRY": {"MODULE_NAME": "NATIVE_BGC_FLEX",
                                "MODULE_CONFIG_FILEPATH": "openwq_in/openWQ_BGC.json"},
            "TRANSPORT_DISSOLVED": {"MODULE_NAME": "NATIVE_TD_ADV",
                                    "MODULE_CONFIG_FILEPATH": "openwq_in/openWQ_TD.json"},
            "LATERAL_EXCHANGE": {"MODULE_NAME": "NONE", "MODULE_CONFIG_FILEPATH": ""},
            "TRANSPORT_SEDIMENTS": {"MODULE_NAME": "NONE",
                                    "SEDIMENT_COMPARTMENT": compartments[0],
                                    "TRANSPORT_COMPARTMENT": compartments[-1],
                                    "MODULE_CONFIG_FILEPATH": ""},
            "SORPTION_ISOTHERM": {"MODULE_NAME": "NONE",
                                  "SEDIMENT_COMPARTMENT": compartments[0],
                                  "MODULE_CONFIG_FILEPATH": ""},
        },
        "OPENWQ_OUTPUT": {
            "RESULTS_FOLDERPATH": "openwq_out/",
            "FORMAT": "HDF5",
            "CHEMICAL_SPECIES": species,
            "UNITS": units,
            "NO_WATER_CONC_FLAG": -9999,
            "EXPORT_SEDIMENT": False,
            "COMPARTMENTS_AND_CELLS": {c: {"1": allcells} for c in compartments},
            "TIMESTEP": list(timestep),
            "FLUXES_CONC_TO_PRINT": {f: {"1": allcells} for f in flux_exports},
        },
    }
    config = {"BIOGEOCHEMISTRY_CONFIGURATION": {}}
    for c in compartments:
        ic = initial_mg_l.get(c, {})
        config["BIOGEOCHEMISTRY_CONFIGURATION"][c] = {
            "CYCLING_FRAMEWORK": ["TRACER_CYCLE"],
            "INITIAL_CONDITIONS": {
                "DATA_FORMAT": "JSON",
                "DATA": {sp: {"1": ["ALL", "ALL", "ALL", float(ic.get(sp, 0.0)), "MG/L"]}
                         for sp in species},
            },
        }
    bgc = {
        "CHEMICAL_SPECIES": {
            "LIST": {str(i + 1): sp for i, sp in enumerate(species + ["DECAYED"])},
            "BGC_GENERAL_MOBILE_SPECIES": species,
        },
        "CYCLING_FRAMEWORKS": {
            "TRACER_CYCLE": {
                "LIST_TRANSFORMATIONS": {"1": "DECAY"},
                "1": {
                    "CONSUMED": species[0],
                    "PRODUCED": "DECAYED",
                    "KINETICS": ["k_dec * %s" % species[0], "1/day"],
                    "PARAMETER_NAMES": ["k_dec"],
                    "PARAMETER_VALUES": {"k_dec": float(decay_per_day)},
                },
            }
        },
    }
    td = {"MODULE_NAME": "NATIVE_TD_ADV",
          "TRANSPORT_CONFIGURATION": {"dispersion_x_m2/s": 0.0, "dispersion_y_m2/s": 0.0,
                                      "dispersion_z_m2/s": 0.0, "characteristic_length_m": 100.0}}

    def dump(name, obj):
        with open(folder / name, "w") as f:
            json.dump(obj, f, indent=2)

    dump("openWQ_master.json", master)
    dump("openwq_in/openWQ_config.json", config)
    dump("openwq_in/openWQ_BGC.json", bgc)
    dump("openwq_in/openWQ_TD.json", td)
    for name in ewf_names:
        conc = ewf_mg_l.get(name, {})
        ewf = {"METADATA": {"Comment": "external water flux %s" % name,
                            "ewf_method_fixedval_source": "python host"}}
        for i, sp in enumerate(species):
            ewf[str(i + 1)] = {
                "DATA_FORMAT": "JSON", "UNITS": "mg/l",
                "EXTERNAL_INPUTFLUX_NAME": name, "CHEMICAL_NAME": sp,
                "DATA": {"1": ["all"] * 9 + [float(conc.get(sp, 0.0))]},
            }
        dump("openwq_in/openWQ_EWF_%s.json" % name, ewf)
    return "openWQ_master.json"


__all__ = ["Host", "LOSS", "case_dir", "Clock", "write_minimal_config"]
